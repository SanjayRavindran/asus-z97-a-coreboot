static u32 fb_rgb(const struct lb_framebuffer *fb, u8 r, u8 g, u8 b)
{
	return ((u32)r << fb->red_mask_pos) |
	       ((u32)g << fb->green_mask_pos) |
	       ((u32)b << fb->blue_mask_pos);
}

static void fb_fill_rect(const struct lb_framebuffer *fb, u32 x, u32 y,
			 u32 w, u32 h, u32 px)
{
	uintptr_t base = (uintptr_t)fb->physical_address;

	if (x >= fb->x_resolution || y >= fb->y_resolution)
		return;
	if (x + w > fb->x_resolution)
		w = fb->x_resolution - x;
	if (y + h > fb->y_resolution)
		h = fb->y_resolution - y;

	for (u32 row = 0; row < h; row++) {
		volatile u32 *dst = (volatile u32 *)(base + (size_t)(y + row) * fb->bytes_per_line);
		for (u32 col = 0; col < w; col++)
			dst[x + col] = px;
	}
}

static void fb_draw_char(const struct lb_framebuffer *fb, u32 x, u32 y,
			 char c, u32 fg, u32 bg)
{
	uintptr_t base = (uintptr_t)fb->physical_address;
	unsigned int idx = (unsigned char)c;

	if (idx < 0x20 || idx > 0x7f)
		idx = '?';
	idx -= 0x20;

	if (x + FONT_W > fb->x_resolution || y + FONT_H > fb->y_resolution)
		return;

	for (u32 row = 0; row < FONT_H; row++) {
		uint8_t bits = font_8x16[idx][row];
		volatile u32 *dst = (volatile u32 *)(base + (size_t)(y + row) * fb->bytes_per_line);
		for (u32 col = 0; col < FONT_W; col++)
			dst[x + col] = (bits & (0x80U >> col)) ? fg : bg;
	}
}

static void fb_draw_str(const struct lb_framebuffer *fb, u32 x, u32 y,
			const char *s, u32 fg, u32 bg)
{
	for (; *s && x + FONT_W <= fb->x_resolution; s++, x += FONT_W)
		fb_draw_char(fb, x, y, *s, fg, bg);
}

static u32 classify_line_color(const struct lb_framebuffer *fb, const char *line)
{
	if (strstr(line, "[ERROR]") || strstr(line, "[CRIT") ||
	    strstr(line, "[ALERT]") || strstr(line, "[EMERG]"))
		return fb_rgb(fb, 0xff, 0x5c, 0x5c);
	if (strstr(line, "[WARN"))
		return fb_rgb(fb, 0xff, 0xd1, 0x5c);
	if (strstr(line, "POST: 0x"))
		return fb_rgb(fb, 0x45, 0xe6, 0xff);
	if (strstr(line, "[NOTE") || strstr(line, "GMA:") ||
	    strstr(line, "Azalia:") || strstr(line, "HWM:") ||
	    strstr(line, "PEG:") || strstr(line, "Z97-A:"))
		return fb_rgb(fb, 0x9c, 0xf2, 0xb8);
	return fb_rgb(fb, 0xc8, 0xd4, 0xe2);
}

static const char *peg_mode_name(unsigned int id)
{
	static const char *const names[] = { "Auto (HW)", "1x16", "2x8", "1x8+2x4" };
	return names[id < ARRAY_SIZE(names) ? id : 0];
}

static void fb_debug_render(void *arg)
{
	static const u8 pause_secs[] = { 0, 2, 5, 10 };

	if (acpi_is_wakeup_s3())
		return;

	const struct lb_framebuffer *fb = get_lb_framebuffer();
	if (!fb || !fb->physical_address ||
	    (uintptr_t)fb->physical_address != fb->physical_address ||
	    fb->bits_per_pixel != 32 ||
	    (uint64_t)fb->x_resolution * 4 > fb->bytes_per_line)
		return;

	const u32 bg = fb_rgb(fb, 0x0b, 0x12, 0x1c);
	const u32 hdr_bg = fb_rgb(fb, 0x13, 0x24, 0x38);
	const u32 hdr_fg = fb_rgb(fb, 0x67, 0xd8, 0xff);
	const u32 sub_fg = fb_rgb(fb, 0xe6, 0xef, 0xf8);
	const u32 foot_fg = fb_rgb(fb, 0xa8, 0xc7, 0xfa);

	u32 max_cols = (fb->x_resolution > 2 * PAD_X) ? (fb->x_resolution - 2 * PAD_X) / FONT_W : 40;
	u32 total_rows = (fb->y_resolution > 2 * PAD_Y) ? (fb->y_resolution - 2 * PAD_Y) / FONT_H : 12;
	if (max_cols >= MAX_COLS)
		max_cols = MAX_COLS - 1;
	u32 log_rows = (total_rows > 5) ? (total_rows - 4) : 1;
	if (log_rows > MAX_LINES)
		log_rows = MAX_LINES;

	/* Parse CBMEM console tail into wrapped lines */
	u32 count = 0;
	u32 cur_len = 0;
	char cur[MAX_COLS];
	char last_post[12] = "n/a";
	bool in_esc = false;

	const struct cbmem_cons_buf *cons = cbmem_find(CBMEM_ID_CONSOLE);
	if (cons && cons->size && cons->size <= (16U << 20)) {
		u32 pos = cons->cursor & ((1U << 28) - 1);
		bool overflow = !!(cons->cursor & (1U << 31));
		if (pos > cons->size)
			pos = cons->size;

		u32 starts[2] = { overflow ? pos : 0, 0 };
		u32 ends[2]   = { overflow ? cons->size : pos, overflow ? pos : 0 };

		for (int seg = 0; seg < 2; seg++) {
			for (u32 i = starts[seg]; i < ends[seg]; i++) {
				unsigned char ch = cons->body[i];
				if (ch == 0x1b) {
					in_esc = true;
					continue;
				}
				if (in_esc) {
					if ((ch >= 'A' && ch <= 'Z') || (ch >= 'a' && ch <= 'z'))
						in_esc = false;
					continue;
				}
				if (ch == '\r' || ch == 0)
					continue;
				if (ch == '\n' || cur_len >= max_cols) {
					cur[cur_len] = '\0';
					const char *p = strstr(cur, "POST: 0x");
					if (p && p[8] && p[9]) {
						snprintf(last_post, sizeof(last_post), "0x%c%c", p[8], p[9]);
					}
					struct fb_log_line *slot = &log_lines[count % log_rows];
					memcpy(slot->text, cur, cur_len + 1);
					slot->color = classify_line_color(fb, cur);
					count++;
					cur_len = 0;
					if (ch == '\n')
						continue;
				}
				if (ch == '\t')
					ch = ' ';
				if (ch >= 0x20 && ch <= 0x7e && cur_len < max_cols)
					cur[cur_len++] = (char)ch;
			}
		}
		if (cur_len > 0) {
			cur[cur_len] = '\0';
			const char *p = strstr(cur, "POST: 0x");
			if (p && p[8] && p[9])
				snprintf(last_post, sizeof(last_post), "0x%c%c", p[8], p[9]);
			struct fb_log_line *slot = &log_lines[count % log_rows];
			memcpy(slot->text, cur, cur_len + 1);
			slot->color = classify_line_color(fb, cur);
			count++;
		}
	}

	/* Paint entire framebuffer cleanly */
	fb_fill_rect(fb, 0, 0, fb->x_resolution, fb->y_resolution, bg);
	fb_fill_rect(fb, 0, 0, fb->x_resolution, PAD_Y + 2 * FONT_H + 6, hdr_bg);

	char hdr1[MAX_COLS];
	char hdr2[MAX_COLS];
	unsigned int peg_id = get_uint_option("peg_bifurcation", 0);
	unsigned int pause_id = get_uint_option("fb_debug_pause", 1);
	if (pause_id >= ARRAY_SIZE(pause_secs))
		pause_id = 1;
	u8 pause_s = pause_secs[pause_id];

	snprintf(hdr1, sizeof(hdr1),
		 "ASUS Z97-A | Coreboot + libgfxinit Verbose/POST Console (%ux%u @ 0x%08x%s)",
		 fb->x_resolution, fb->y_resolution, (u32)fb->physical_address,
		 fb->flags.has_dual_pipe ? ", Dual-Pipe" : "");
	snprintf(hdr2, sizeof(hdr2),
		 "Last POST: %s | PEG: %s | Above-4G + ReBar(32G) + SR-IOV | Log lines: %u",
		 last_post, peg_mode_name(peg_id), count);

	fb_draw_str(fb, PAD_X, PAD_Y, hdr1, hdr_fg, hdr_bg);
	fb_draw_str(fb, PAD_X, PAD_Y + FONT_H, hdr2, sub_fg, hdr_bg);

	u32 start_idx = (count > log_rows) ? (count - log_rows) : 0;
	u32 y = PAD_Y + 2 * FONT_H + 10;
	for (u32 n = start_idx; n < count; n++, y += FONT_H) {
		const struct fb_log_line *slot = &log_lines[n % log_rows];
		fb_draw_str(fb, PAD_X, y, slot->text, slot->color, bg);
	}

	char footer[MAX_COLS];
	snprintf(footer, sizeof(footer),
		 "Next: UEFI POST Menu (5s) -> Press ESC for UEFI Setup/CFR | DEL for Boot Menu | ENTER to Boot (%us)",
		 pause_s);
	fb_fill_rect(fb, 0, fb->y_resolution - (PAD_Y + FONT_H + 4),
		     fb->x_resolution, PAD_Y + FONT_H + 4, hdr_bg);
	fb_draw_str(fb, PAD_X, fb->y_resolution - (PAD_Y + FONT_H), footer, foot_fg, hdr_bg);

	printk(BIOS_INFO, "FB_CONSOLE: rendered %ux%u debug log (%u lines, last_post=%s, pause=%us)\n",
	       fb->x_resolution, fb->y_resolution, count, last_post, pause_s);

	if (pause_s > 0)
		mdelay((unsigned int)pause_s * 1000U);

	/* Clear framebuffer before EDK2 handoff so centered UEFI text never overlaps */
	fb_fill_rect(fb, 0, 0, fb->x_resolution, fb->y_resolution, 0);
}

BOOT_STATE_INIT_ENTRY(BS_PAYLOAD_LOAD, BS_ON_ENTRY, fb_debug_render, NULL);
